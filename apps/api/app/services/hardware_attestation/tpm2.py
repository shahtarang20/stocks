"""TPM 2.0 Quote Verifier (WP-F / F2).

Evidence (hex strings):

    {"quote": {"attest": <TPMS_ATTEST bytes the AK signed>,
               "signature": <RSASSA / RSAPSS signature bytes, or DER ECDSA>,
               "ak_public": <TPMT_PUBLIC bytes of the AK>},
     "pcrs": {"<index>": <SHA-256 PCR value>, ...},
     "ek_cert": <PEM>, "ek_intermediates": [<PEM>, ...]}

Checks, in order:
1. the EK certificate chains to a PINNED TPM-vendor root;
2. the AK is the one bound to this machine's EK at enrolment (``context["bound_ak_name"]``, the
   TPM name 0x000B || SHA-256(TPMT_PUBLIC)). An EK is a decrypt-only key and never signs an AK,
   so binding is done once with TPM2_MakeCredential / TPM2_ActivateCredential and recorded;
   without that record nothing verifies;
3. the AK is a restricted, fixedTPM signing key, and its signature covers ``attest``;
4. everything below is PARSED FROM ``attest`` (the signed bytes): TPM_GENERATED magic, the quote
   type, extraData == SHA-256(nonce), the PCR selection and its digest;
5. the reported PCR values hash to that digest, and every expected PCR is in the signed selection.
"""

from __future__ import annotations

import hashlib
import struct
from dataclasses import dataclass
from typing import Any

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec, padding, rsa

from app.services.hardware_attestation import (
    HardwareAttestationError,
    HardwareAttestationResult,
    load_pem_certificate,
    verify_chain,
)

TPM_GENERATED_VALUE = 0xFF544347
TPM_ST_ATTEST_QUOTE = 0x8018
TPM_ALG_RSA, TPM_ALG_ECC, TPM_ALG_SHA256, TPM_ALG_NULL = 0x0001, 0x0023, 0x000B, 0x0010
TPM_ECC_NIST_P256, TPM_ECC_NIST_P384 = 0x0003, 0x0004

# TPMA_OBJECT bits an attestation key must have / must not have.
FIXED_TPM, FIXED_PARENT, SENSITIVE_DATA_ORIGIN = 1 << 1, 1 << 4, 1 << 5
RESTRICTED, DECRYPT, SIGN = 1 << 16, 1 << 17, 1 << 18
_AK_REQUIRED = FIXED_TPM | FIXED_PARENT | SENSITIVE_DATA_ORIGIN | RESTRICTED | SIGN


class _Reader:
    """Big-endian TPM marshalling reader that fails closed on truncation."""

    def __init__(self, data: bytes):
        self.data, self.pos = data, 0

    def take(self, n: int) -> bytes:
        if n < 0 or self.pos + n > len(self.data):
            raise HardwareAttestationError("tpm2_malformed_quote", "truncated TPM structure")
        out = self.data[self.pos:self.pos + n]
        self.pos += n
        return out

    def u8(self) -> int:
        return self.take(1)[0]

    def u16(self) -> int:
        return struct.unpack(">H", self.take(2))[0]

    def u32(self) -> int:
        return struct.unpack(">I", self.take(4))[0]

    def u64(self) -> int:
        return struct.unpack(">Q", self.take(8))[0]

    def tpm2b(self) -> bytes:
        return self.take(self.u16())

    def done(self) -> bool:
        return self.pos == len(self.data)


@dataclass(frozen=True)
class QuoteInfo:
    extra_data: bytes
    selection: dict[int, list[int]]  # hash alg -> PCR indices, ascending
    pcr_digest: bytes
    clock: int
    reset_count: int
    restart_count: int


def parse_tpms_attest(attest: bytes) -> QuoteInfo:
    r = _Reader(attest)
    if r.u32() != TPM_GENERATED_VALUE:
        raise HardwareAttestationError("tpm2_malformed_quote", "attestation was not generated by a TPM (bad magic)")
    if r.u16() != TPM_ST_ATTEST_QUOTE:
        raise HardwareAttestationError("tpm2_malformed_quote", "attestation is not a quote")
    r.tpm2b()  # qualifiedSigner
    extra = r.tpm2b()
    clock, reset_count, restart_count, _safe = r.u64(), r.u32(), r.u32(), r.u8()
    r.u64()  # firmwareVersion
    selection: dict[int, list[int]] = {}
    for _ in range(r.u32()):
        alg = r.u16()
        bitmap = r.take(r.u8())
        selection.setdefault(alg, []).extend(
            i * 8 + b for i, byte in enumerate(bitmap) for b in range(8) if byte >> b & 1
        )
    digest = r.tpm2b()
    if not r.done():
        raise HardwareAttestationError("tpm2_malformed_quote", "trailing bytes after TPMS_ATTEST")
    return QuoteInfo(extra, {a: sorted(set(v)) for a, v in selection.items()}, digest, clock, reset_count, restart_count)


def tpm_name(tpmt_public: bytes) -> bytes:
    """TPM2 object name for a SHA-256 nameAlg: 0x000B || SHA-256(TPMT_PUBLIC)."""
    return struct.pack(">H", TPM_ALG_SHA256) + hashlib.sha256(tpmt_public).digest()


def parse_ak_public(tpmt_public: bytes) -> Any:
    """The AK's public key from its TPMT_PUBLIC, after checking it is a restricted signing key."""
    r = _Reader(tpmt_public)
    key_type, name_alg, attrs = r.u16(), r.u16(), r.u32()
    r.tpm2b()  # authPolicy
    if name_alg != TPM_ALG_SHA256:
        raise HardwareAttestationError("tpm2_bad_ak", "AK nameAlg must be SHA-256")
    if attrs & _AK_REQUIRED != _AK_REQUIRED or attrs & DECRYPT:
        raise HardwareAttestationError("tpm2_bad_ak", "AK must be a restricted, fixedTPM signing key")
    if r.u16() != TPM_ALG_NULL:  # symmetric: a signing key has none
        raise HardwareAttestationError("tpm2_bad_ak", "AK must not have a symmetric algorithm")
    scheme = r.u16()
    if scheme != TPM_ALG_NULL:
        r.u16()  # scheme hash
    if key_type == TPM_ALG_RSA:
        bits, exponent = r.u16(), r.u32() or 65537
        modulus = r.tpm2b()
        if bits < 2048 or len(modulus) * 8 != bits:
            raise HardwareAttestationError("tpm2_bad_ak", "AK RSA modulus is malformed or too small")
        key = rsa.RSAPublicNumbers(exponent, int.from_bytes(modulus, "big")).public_key()
    elif key_type == TPM_ALG_ECC:
        curve_id = r.u16()
        if r.u16() != TPM_ALG_NULL:  # kdf
            raise HardwareAttestationError("tpm2_bad_ak", "AK must not have a KDF")
        x, y = r.tpm2b(), r.tpm2b()
        curve = {TPM_ECC_NIST_P256: ec.SECP256R1(), TPM_ECC_NIST_P384: ec.SECP384R1()}.get(curve_id)
        if curve is None:
            raise HardwareAttestationError("tpm2_bad_ak", "AK curve is not P-256 or P-384")
        try:
            key = ec.EllipticCurvePublicNumbers(int.from_bytes(x, "big"), int.from_bytes(y, "big"), curve).public_key()
        except ValueError as exc:
            raise HardwareAttestationError("tpm2_bad_ak", "AK point is not on the curve") from exc
    else:
        raise HardwareAttestationError("tpm2_bad_ak", "AK must be RSA or ECC")
    if not r.done():
        raise HardwareAttestationError("tpm2_bad_ak", "trailing bytes after TPMT_PUBLIC")
    return key


def _signature_ok(key: Any, data: bytes, signature: bytes) -> bool:
    try:
        if isinstance(key, rsa.RSAPublicKey):
            for pad in (padding.PKCS1v15(), padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=padding.PSS.AUTO)):
                try:
                    key.verify(signature, data, pad, hashes.SHA256())
                    return True
                except InvalidSignature:
                    continue
            return False
        key.verify(signature, data, ec.ECDSA(hashes.SHA256()))
        return True
    except (InvalidSignature, ValueError, TypeError):
        return False


def _hex(value: Any) -> bytes:
    try:
        return bytes.fromhex(value) if isinstance(value, str) else b""
    except ValueError:
        return b""


def _pcr_index(key: str) -> int | None:
    k = str(key).lower().removeprefix("pcr")
    return int(k) if k.isdigit() else None


class TPM2Verifier:
    """Fail-closed verifier for TPM 2.0 quotes."""

    def verify(
        self,
        evidence: dict[str, Any],
        nonce: str,
        expected_measurements: dict[str, str] | None,
        root_certs: list,
        context: dict[str, Any] | None = None,
    ) -> HardwareAttestationResult:
        if not isinstance(evidence, dict) or not isinstance(evidence.get("quote"), dict):
            raise HardwareAttestationError("tpm2_malformed_evidence", "evidence must contain a quote")
        quote = evidence["quote"]

        # 1. EK chain to a pinned TPM vendor root.
        ek_cert = load_pem_certificate(evidence.get("ek_cert"), "EK certificate")
        intermediates = [load_pem_certificate(p, "EK intermediate") for p in evidence.get("ek_intermediates") or []]
        verify_chain(ek_cert, intermediates, root_certs, code="tpm2_bad_certificate_chain")

        # 2. The AK is the one enrolled for this machine's EK.
        ak_public = _hex(quote.get("ak_public"))
        bound = (context or {}).get("bound_ak_name")
        if not bound:
            raise HardwareAttestationError("tpm2_ak_not_enrolled", "no AK has been bound to this machine's EK (credential activation)")
        if not ak_public or tpm_name(ak_public).hex() != str(bound).lower():
            raise HardwareAttestationError("tpm2_unbound_ak", "the quoting AK is not the AK bound to this machine's EK")
        ak_key = parse_ak_public(ak_public)

        # 3. AK signature over the attest bytes.
        attest, signature = _hex(quote.get("attest")), _hex(quote.get("signature"))
        if not attest or not signature or not _signature_ok(ak_key, attest, signature):
            raise HardwareAttestationError("tpm2_invalid_signature", "AK signature over the quote does not verify")

        # 4. Everything else comes from the signed bytes.
        info = parse_tpms_attest(attest)
        if info.extra_data != hashlib.sha256(nonce.encode("utf-8")).digest():
            raise HardwareAttestationError("tpm2_wrong_nonce", "quote is not bound to this challenge")
        if set(info.selection) != {TPM_ALG_SHA256} or not info.selection[TPM_ALG_SHA256]:
            raise HardwareAttestationError("tpm2_malformed_quote", "quote must select SHA-256 PCRs only")
        selected = info.selection[TPM_ALG_SHA256]

        # 5. Reported PCR values must hash to the signed digest; only selected PCRs count.
        reported: dict[int, bytes] = {}
        for k, v in (evidence.get("pcrs") or {}).items():
            idx, val = _pcr_index(k), _hex(v)
            if idx is None or len(val) != 32:
                raise HardwareAttestationError("tpm2_malformed_evidence", f"PCR {k!r} is not a SHA-256 value")
            reported[idx] = val
        if any(i not in reported for i in selected):
            raise HardwareAttestationError("tpm2_missing_pcr", "a PCR in the signed selection was not reported")
        if hashlib.sha256(b"".join(reported[i] for i in selected)).digest() != info.pcr_digest:
            raise HardwareAttestationError("tpm2_pcr_mismatch", "reported PCRs do not match the signed PCR digest")
        measurements = {f"pcr{i}": reported[i].hex() for i in selected}
        for k, expected in (expected_measurements or {}).items():
            idx = _pcr_index(k)
            if idx is None or idx not in selected:
                raise HardwareAttestationError("tpm2_pcr_not_quoted", f"expected PCR {k} is not covered by the quote")
            if measurements[f"pcr{idx}"] != str(expected).lower():
                raise HardwareAttestationError("tpm2_pcr_mismatch", f"PCR {idx} does not have the expected value")

        return HardwareAttestationResult(
            flavor="tpm2",
            verified=True,
            measurements=measurements,
            public_key=tpm_name(ak_public).hex(),
            security_features={
                "tpm_version": "2.0",
                "clock": info.clock,
                "reset_count": info.reset_count,
                "restart_count": info.restart_count,
                "ek_subject": ek_cert.subject.rfc4514_string(),
            },
        )
