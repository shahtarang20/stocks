"use client";

import { useState } from "react";
import { useMutation, useQuery } from "@tanstack/react-query";
import { Download, ShieldCheck } from "lucide-react";
import { Card, CardContent } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { api, apiAbsoluteUrl, type Job, type JobArtifact, type JobLogs, type LogLine } from "@/lib/api";
import { isJobActive, jobStatusLabel, jobStatusHelp, logLineText } from "@/lib/jobs";
import { formatBytes, formatRelativeTime } from "@/lib/utils";
import { dataApi, isDataPlaneDisabled, verificationLabel, type DataFile } from "@/lib/kits";

/** Progress as 0..100, tolerant of a 0..1 fraction or a percentage; null when the API reports none. */
export function progressPercent(job: Job): number | null {
  const raw = (job as Record<string, unknown>).progress;
  const n = typeof raw === "number" ? raw : typeof raw === "object" && raw && typeof (raw as { fraction?: unknown }).fraction === "number" ? (raw as { fraction: number }).fraction : null;
  if (n === null || !Number.isFinite(n)) return null;
  return Math.max(0, Math.min(100, Math.round(n <= 1 ? n * 100 : n)));
}

function costSoFar(job: Job): string | null {
  const v = (job as Record<string, unknown>).cost_so_far ?? job.final_cost;
  return v === null || v === undefined ? null : String(v);
}

function logsOf(l: JobLogs | undefined): LogLine[] {
  if (!l) return [];
  return Array.isArray(l) ? l : l.lines ?? [];
}

function Preview({ token, jobId, artifact }: { token: string; jobId: string; artifact: JobArtifact }) {
  const isImage = artifact.content_type.startsWith("image/");
  const isVideo = artifact.content_type.startsWith("video/");
  const q = useQuery({
    queryKey: ["kit-preview", jobId, artifact.artifact_id],
    enabled: (isImage || isVideo) && artifact.size <= 200 * 1024 * 1024,
    queryFn: () => api.getArtifactDownloadUrl(token, jobId, artifact.artifact_id),
    staleTime: 4 * 60 * 1000,
    retry: false,
  });
  if (!q.data?.url) return null;
  const src = apiAbsoluteUrl(q.data.url);
  return isImage ? (
    // eslint-disable-next-line @next/next/no-img-element
    <img src={src} alt={`Preview of ${artifact.kind}`} className="max-h-72 w-full rounded-md border border-border object-contain" />
  ) : (
    // Job output is generated by the Kit and has no caption track to offer.
    // eslint-disable-next-line jsx-a11y/media-has-caption
    <video src={src} controls preload="metadata" aria-label={`Preview of ${artifact.kind}`} className="max-h-72 w-full rounded-md border border-border" />
  );
}

/** Live view of a Kit job: progress, cost, logs, previews, scoped download links, verification. */
export function KitJobPanel({ job, token }: { job: Job; token: string }) {
  const jobId = job.job_id ?? (job.id as string);
  const active = isJobActive(job.status);
  const [linkInfo, setLinkInfo] = useState<Record<string, string>>({});

  const logs = useQuery<JobLogs>({
    queryKey: ["job-logs", jobId],
    queryFn: () => api.getJobLogs(token, jobId),
    refetchInterval: active ? 4000 : false,
  });
  const artifacts = useQuery<JobArtifact[]>({
    queryKey: ["job-artifacts", jobId],
    queryFn: () => api.getJobArtifacts(token, jobId),
    refetchInterval: active ? 6000 : false,
  });
  // A Kit job's outputs are not v1 artifacts: the agent uploads each one to the customer's file store as out/<job_id>/<name>.
  const outputFiles = useQuery<DataFile[]>({
    queryKey: ["job-output-files", jobId],
    queryFn: () => dataApi.listFiles(token, { namePrefix: `out/${jobId}/` }),
    refetchInterval: active ? 6000 : false,
    retry: (n, err) => !isDataPlaneDisabled(err) && n < 2,
  });
  const fileDownload = useMutation({
    mutationFn: (f: DataFile) => dataApi.downloadLink(token, f.id),
    onSuccess: (res, f) => {
      setLinkInfo((m) => ({ ...m, [f.id]: res.expires_at ? `Link expires ${formatRelativeTime(res.expires_at)}.` : "This link expires soon." }));
      if (res?.url) window.open(res.url, "_blank", "noopener,noreferrer");
    },
  });
  const download = useMutation({
    mutationFn: (a: JobArtifact) => api.getArtifactDownloadUrl(token, jobId, a.artifact_id),
    onSuccess: (res, a) => {
      setLinkInfo((m) => ({ ...m, [a.artifact_id]: res.expires_at ? `Link expires ${formatRelativeTime(res.expires_at)}.` : "This link expires soon." }));
      if (res?.url) window.open(apiAbsoluteUrl(res.url), "_blank", "noopener,noreferrer");
    },
  });

  const pct = progressPercent(job);
  const cost = costSoFar(job);
  const lines = logsOf(logs.data).slice(-200).map(logLineText);
  const list = artifacts.data ?? [];
  const files = outputFiles.data ?? [];
  const verification = (job.verification ?? null) as Record<string, unknown> | null;
  const spec = (job as Record<string, unknown>).spec_v2 as { kit_image?: string } | undefined;

  return (
    <Card>
      <CardContent className="space-y-6 p-4 sm:p-6">
        <section aria-labelledby="kj-progress">
          <h2 id="kj-progress" className="text-lg font-semibold">Progress</h2>
          <div
            role="progressbar"
            aria-labelledby="kj-progress"
            aria-valuemin={0}
            aria-valuemax={100}
            aria-valuenow={pct ?? (active ? undefined : 100)}
            aria-valuetext={pct === null ? (active ? "Working" : job.status) : `${pct} percent`}
            className="mt-3 h-3 overflow-hidden rounded-full bg-border"
          >
            <div
              className={`h-full bg-primary ${pct === null && active ? "w-1/3 animate-pulse" : ""}`}
              style={pct === null ? (active ? undefined : { width: job.status === "completed" ? "100%" : "0%" }) : { width: `${pct}%` }}
            />
          </div>
          <p className="mt-2 text-sm text-muted-foreground" role="status" aria-live="polite">
            {pct !== null ? `${pct}% done. ` : ""}
            {active ? "This updates by itself every few seconds." : `Finished: ${jobStatusLabel(job.status).toLowerCase()}. ${jobStatusHelp(job.status)}`}
          </p>
        </section>

        <dl className="grid gap-4 text-sm sm:grid-cols-3">
          <div>
            <dt className="text-muted-foreground">Cost so far</dt>
            <dd className="mt-0.5 text-base font-medium">{cost ?? "Nothing charged yet"}</dd>
          </div>
          <div>
            <dt className="text-muted-foreground">Most you agreed to pay</dt>
            <dd className="mt-0.5 text-base font-medium">{job.max_cost ?? "no limit set"}</dd>
          </div>
          <div>
            <dt className="text-muted-foreground">Kit (ready-made tool)</dt>
            <dd className="mt-0.5 break-all font-mono text-xs">{String((job as Record<string, unknown>).kit ?? job.model)}</dd>
          </div>
        </dl>

        <section aria-labelledby="kj-results">
          <h2 id="kj-results" className="text-lg font-semibold">Results</h2>
          {list.length === 0 && files.length === 0 ? (
            <p className="mt-2 text-sm text-muted-foreground">
              {active ? "Results appear here as soon as they are ready." : "This job did not make any files. Check the log below to see why."}
            </p>
          ) : (
            <ul className="mt-3 space-y-4">
              {files.map((f) => (
                <li key={f.id} className="rounded-md border border-border p-3">
                  <div className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
                    <div className="min-w-0">
                      <p className="break-words text-sm font-medium">{f.name.replace(`out/${jobId}/`, "")}</p>
                      <p className="text-xs text-muted-foreground">{f.content_type} · {formatBytes(f.size_bytes)}</p>
                    </div>
                    <Button
                      type="button"
                      variant="outline"
                      className="w-full sm:w-auto"
                      disabled={fileDownload.isPending}
                      onClick={() => fileDownload.mutate(f)}
                    >
                      <Download /> Download
                    </Button>
                  </div>
                  <p className="mt-2 text-xs text-muted-foreground" aria-live="polite">
                    {linkInfo[f.id] ?? "Each download link is private to you and expires after a short time."}
                  </p>
                </li>
              ))}
              {list.map((a) => (
                <li key={a.artifact_id} className="rounded-md border border-border p-3">
                  <div className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
                    <div className="min-w-0">
                      <p className="break-words text-sm font-medium">{a.kind}</p>
                      <p className="text-xs text-muted-foreground">{a.content_type} · {formatBytes(a.size)}</p>
                    </div>
                    <Button
                      type="button"
                      variant="outline"
                      className="w-full sm:w-auto"
                      disabled={download.isPending}
                      onClick={() => download.mutate(a)}
                    >
                      <Download /> Download
                    </Button>
                  </div>
                  <div className="mt-3"><Preview token={token} jobId={jobId} artifact={a} /></div>
                  <p className="mt-2 text-xs text-muted-foreground" aria-live="polite">
                    {linkInfo[a.artifact_id] ?? "Each download link is private to you and expires after a short time."}
                  </p>
                </li>
              ))}
            </ul>
          )}
          {download.isError || fileDownload.isError ? <p role="alert" className="mt-2 text-sm text-danger">We could not make a download link. Please press Download again.</p> : null}
        </section>

        <section aria-labelledby="kj-verify">
          <h2 id="kj-verify" className="flex items-center gap-2 text-lg font-semibold">
            <ShieldCheck aria-hidden="true" className="h-5 w-5" /> How this was checked
          </h2>
          {verification ? (
            <dl className="mt-2 grid gap-2 text-sm sm:grid-cols-2">
              {Object.entries(verification).slice(0, 8).map(([k, v]) => (
                <div key={k}>
                  <dt className="text-muted-foreground">{k === "method" ? "Method" : k.replace(/_/g, " ")}</dt>
                  <dd className="break-words font-medium">
                    {k === "method" ? verificationLabel(String(v)) : typeof v === "object" ? JSON.stringify(v) : String(v)}
                  </dd>
                </div>
              ))}
            </dl>
          ) : (
            <p className="mt-2 text-sm text-muted-foreground">
              {active ? "The checks appear here when the job finishes." : "No check result was saved for this job."}
            </p>
          )}
          {spec?.kit_image ? <p className="mt-2 break-all font-mono text-xs text-muted-foreground">Tool version: {spec.kit_image}</p> : null}
        </section>

        <section aria-labelledby="kj-logs">
          <h2 id="kj-logs" className="text-lg font-semibold">
            Log <Badge variant="neutral" className="ml-2 align-middle">{lines.length} lines</Badge>
          </h2>
          <pre
            role="log"
            aria-labelledby="kj-logs"
            // A scrollable region must be keyboard-focusable (WCAG 2.1.1), so keep it in the tab order.
            // eslint-disable-next-line jsx-a11y/no-noninteractive-tabindex
            tabIndex={0}
            className="mt-2 max-h-72 overflow-auto whitespace-pre-wrap break-words rounded-md border border-border bg-surface-2 p-3 font-mono text-xs focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
          >
            {lines.length ? lines.join("\n") : active ? "Waiting for the computer to report…" : "Nothing was written to the log."}
          </pre>
        </section>
      </CardContent>
    </Card>
  );
}
